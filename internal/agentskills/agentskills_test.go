package agentskills_test

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/goccy/go-yaml"
	"github.com/romshark/toki/internal/agentskills"
	"github.com/stretchr/testify/require"
)

var project = agentskills.Project{
	BundleDir:        "tokibundle",
	BundleImportPath: "example.com/app/tokibundle",
	DefaultLocale:    "en",
	NativeCatalog:    "catalog_en.arb",
}

var skillFiles = []string{
	".claude/skills/toki/SKILL.md",
	".agents/skills/toki/SKILL.md",
	".claude/skills/toki-translate/SKILL.md",
	".agents/skills/toki-translate/SKILL.md",
}

func TestWrite(t *testing.T) {
	dir := t.TempDir()
	written, err := agentskills.Write(dir, project)
	require.NoError(t, err)
	require.ElementsMatch(t, fromSlash(skillFiles), written)

	for _, f := range skillFiles {
		t.Run(f, func(t *testing.T) {
			content := readFile(t, dir, f)
			front, body, ok := strings.Cut(strings.TrimPrefix(content, "---\n"), "\n---\n")
			require.True(t, ok && strings.HasPrefix(content, "---\n"),
				"no frontmatter: %q", content)

			var meta struct{ Name, Description string }
			require.NoError(t, yaml.Unmarshal([]byte(front), &meta))
			// Agents require the name of a skill to match its directory.
			require.Equal(t, filepath.Base(filepath.Dir(f)), meta.Name)
			require.NotEmpty(t, meta.Description)
			require.LessOrEqual(t, len(meta.Description), 1024)

			require.True(t, strings.HasPrefix(body,
				"\n<!-- Generated by github.com/romshark/toki. DO NOT EDIT."),
				"no generated header below the frontmatter: %q", body)
			require.Contains(t, body, "`tokibundle/")
			require.Contains(t, body, "`catalog_en.arb`")
			require.NotContains(t, body, "<no value>")
			require.NotContains(t, body, "\n\n\n")
			require.True(t, strings.HasSuffix(body, "\n") && !strings.HasSuffix(body, "\n\n"),
				"doesn't end with 1 line break")
		})
	}
	require.Contains(t, readFile(t, dir, skillFiles[0]), "`example.com/app/tokibundle`")

	// Every agent reads the same skills.
	require.Equal(t, readFile(t, dir, skillFiles[0]), readFile(t, dir, skillFiles[1]))
	require.Equal(t, readFile(t, dir, skillFiles[2]), readFile(t, dir, skillFiles[3]))
}

// TestWriteOverwrites makes sure Write leaves files as they are when they hold
// the skills already and replaces edited ones.
func TestWriteOverwrites(t *testing.T) {
	dir := t.TempDir()
	_, err := agentskills.Write(dir, project)
	require.NoError(t, err)
	original := readFile(t, dir, skillFiles[0])

	written, err := agentskills.Write(dir, project)
	require.NoError(t, err)
	require.Empty(t, written)

	edited := filepath.Join(dir, skillFiles[0])
	require.NoError(t, os.WriteFile(edited, []byte("edited"), 0o644))
	written, err = agentskills.Write(dir, project)
	require.NoError(t, err)
	require.Equal(t, fromSlash(skillFiles[:1]), written)
	require.Equal(t, original, readFile(t, dir, skillFiles[0]))
}

func TestWriteProject(t *testing.T) {
	t.Run("defaults", func(t *testing.T) {
		dir := t.TempDir()
		_, err := agentskills.Write(dir, project)
		require.NoError(t, err)
		for _, f := range skillFiles {
			content := readFile(t, dir, f)
			require.Contains(t, content, "toki generate #")
			require.Contains(t, content, "go run github.com/romshark/toki@latest")
			require.NotContains(t, content, "toki version")
		}
	})

	t.Run("bundle and release", func(t *testing.T) {
		dir := t.TempDir()
		p := project
		p.BundleDir = "internal/i18n"
		p.BundleImportPath = "example.com/app/internal/i18n"
		p.Flags = " -b internal/i18n"
		p.Version = "v1.2.3"
		_, err := agentskills.Write(dir, p)
		require.NoError(t, err)
		for _, f := range skillFiles {
			content := readFile(t, dir, f)
			require.Contains(t, content, "toki generate -b internal/i18n #")
			require.Contains(t, content, "`internal/i18n/`")
			require.Contains(t, content, "go run github.com/romshark/toki@v1.2.3")
			require.NotContains(t, content, "@latest")
		}
		require.Contains(t, readFile(t, dir, skillFiles[0]), "i18n.Match(")
	})
}

func readFile(t *testing.T, dir, name string) string {
	t.Helper()
	b, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(name)))
	require.NoError(t, err)
	return string(b)
}

func fromSlash(paths []string) []string {
	s := make([]string, len(paths))
	for i, p := range paths {
		s[i] = filepath.FromSlash(p)
	}
	return s
}
